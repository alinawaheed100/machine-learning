import numpy as np

# Make a copy for cleaning
df_clean = df.copy()

# 1. Clean 'Total Fat (g)' - remove potential non-numeric values and convert to float
df_clean['Total Fat (g)'] = pd.to_numeric(df_clean['Total Fat (g)'].astype(str).str.replace(r'[^0-9.]', '', regex=True), errors='coerce')

# 2. Clean '% DV' columns - remove '%' sign and convert to float
dv_cols = ['Vitamin A (% DV)', 'Vitamin C (% DV)', 'Calcium (% DV)', 'Iron (% DV)']
for col in dv_cols:
    df_clean[col] = pd.to_numeric(df_clean[col].astype(str).str.replace('%', ''), errors='coerce')

# 3. Clean 'Caffeine (mg)' - replace values like 'Varies' or 'varies' with NaN, then convert
df_clean['Caffeine (mg)'] = pd.to_numeric(df_clean['Caffeine (mg)'].astype(str).str.replace('Varies', 'NaN', case=False), errors='coerce')

# Fill missing values created during conversions with the median of their respective columns
num_cols_to_fill = ['Total Fat (g)', 'Caffeine (mg)'] + dv_cols
for col in num_cols_to_fill:
    df_clean[col] = df_clean[col].fillna(df_clean[col].median())

print("=== Cleaned Data Types and Missing Values ===")
print(df_clean[num_cols_to_fill].dtypes)
print("\nAny missing values left?", df_clean.isnull().any().any())

